/**
 * The allowlist is intentionally narrow. Any channel not proven safe for an
 * unlicensed installation is paid by default, so new execution or mutation
 * surfaces cannot accidentally bypass licensing.
 */
export function classifyArtistOSLicenseChannel(channel: string): ArtistOSLicenseChannelClass {
  return ALWAYS_REACHABLE_CHANNELS.has(channel) ? 'always-reachable' : 'paid';
}

export function isArtistOSPaidChannel(channel: string): boolean {
  return classifyArtistOSLicenseChannel(channel) === 'paid';
}
